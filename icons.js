// Recibe un root para poder hidratar también el contenido de los <template>.
// Usa DOMParser en vez de innerHTML (lo pide el linter de Mozilla).
const svgParser = new DOMParser();
function hydrateIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((el) => {
    const inner = LUCIDE[el.dataset.icon];
    if (!inner) return;
    const doc = svgParser.parseFromString(
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" ` +
      `stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${inner}</svg>`,
      "image/svg+xml",
    );
    el.replaceChildren(el.ownerDocument.importNode(doc.documentElement, true));
  });
}
